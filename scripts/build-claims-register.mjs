// Builds the medical-claims substantiation register from per-domain source
// fragments in data/claims-src/*.json into:
//   • data/medical-claims-register.json  (machine-readable)
//   • docs/medical-claims-register.md     (human-readable report)
//
// Re-run after editing any fragment (e.g. during a periodic stale-evidence
// review): `node scripts/build-claims-register.mjs`.
//
// Each fragment is a JSON array of claim entries with fields:
//   id, page_url, page_title, claim_text, category, risk (LOW|MODERATE|HIGH),
//   status (supported|needs_qualification|change_recommended|changed|
//           needs_review|removed), wording_acceptable, recommended_wording,
//   primary_source {org,title,url,date}, supporting_source, evidence_summary,
//   limitations, reviewer_notes, last_verified, review_due
import { readdir, readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "data", "claims-src");
const OUT_JSON = path.join(ROOT, "data", "medical-claims-register.json");
const OUT_MD = path.join(ROOT, "docs", "medical-claims-register.md");
const RISK_ORDER = { HIGH: 0, MODERATE: 1, LOW: 2 };

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
const src = (s) =>
  s && s.org ? `${esc(s.org)}${s.url ? ` ([link](${s.url}))` : ""}${s.date ? ` — ${esc(s.date)}` : ""}` : "—";

async function main() {
  let files = [];
  try {
    files = (await readdir(SRC)).filter((f) => f.endsWith(".json")).sort();
  } catch {
    console.error(`No source dir ${SRC}`);
    process.exit(1);
  }

  const entries = [];
  for (const f of files) {
    const raw = await readFile(path.join(SRC, f), "utf8");
    let arr;
    try {
      arr = JSON.parse(raw);
    } catch (e) {
      console.error(`✗ ${f}: invalid JSON (${e.message})`);
      process.exit(1);
    }
    if (!Array.isArray(arr)) {
      console.error(`✗ ${f}: expected a JSON array`);
      process.exit(1);
    }
    entries.push(...arr);
  }

  entries.sort(
    (a, b) =>
      (RISK_ORDER[a.risk] ?? 3) - (RISK_ORDER[b.risk] ?? 3) ||
      String(a.id).localeCompare(String(b.id)),
  );

  const by = (k, v) => entries.filter((e) => e[k] === v).length;
  const changed = entries.filter((e) =>
    ["change_recommended", "changed"].includes(e.status),
  );
  const review = entries.filter((e) => e.status === "needs_review");
  const totals = {
    generated: new Date().toISOString().slice(0, 10),
    total_claims: entries.length,
    by_risk: { HIGH: by("risk", "HIGH"), MODERATE: by("risk", "MODERATE"), LOW: by("risk", "LOW") },
    by_status: {
      supported: by("status", "supported"),
      needs_qualification: by("status", "needs_qualification"),
      change_recommended: by("status", "change_recommended"),
      changed: by("status", "changed"),
      needs_review: by("status", "needs_review"),
      removed: by("status", "removed"),
    },
  };

  await mkdir(path.dirname(OUT_JSON), { recursive: true });
  await writeFile(
    OUT_JSON,
    JSON.stringify({ meta: totals, claims: entries }, null, 2) + "\n",
  );

  // ── Markdown report ──
  const L = [];
  L.push("# Medical claims & substantiation register");
  L.push("");
  L.push(
    "> Internal evidence trail for medical/health claims on dramandahenderson.com.au.",
  );
  L.push(
    "> Generated by `scripts/build-claims-register.mjs` from `data/claims-src/`. Do not edit by hand — edit the fragments and rebuild.",
  );
  L.push("");
  L.push(`**Generated:** ${totals.generated}  |  **Total claims:** ${totals.total_claims}`);
  L.push("");
  L.push("## Executive summary");
  L.push("");
  L.push("| Metric | Count |");
  L.push("|---|---|");
  L.push(`| High risk | ${totals.by_risk.HIGH} |`);
  L.push(`| Moderate risk | ${totals.by_risk.MODERATE} |`);
  L.push(`| Low risk | ${totals.by_risk.LOW} |`);
  L.push(`| Supported as written | ${totals.by_status.supported} |`);
  L.push(`| Needs qualification | ${totals.by_status.needs_qualification} |`);
  L.push(`| Wording changed | ${totals.by_status.changed} |`);
  L.push(`| Change recommended (not yet applied) | ${totals.by_status.change_recommended} |`);
  L.push(`| Needs specialist/legal review | ${totals.by_status.needs_review} |`);
  L.push(`| Removed | ${totals.by_status.removed} |`);
  L.push("");

  L.push("## High-risk claims");
  L.push("");
  L.push("| ID | Page | Claim | Status | Primary source |");
  L.push("|---|---|---|---|---|");
  for (const e of entries.filter((e) => e.risk === "HIGH")) {
    L.push(
      `| ${e.id} | ${esc(e.page_url)} | ${esc(e.claim_text)} | ${esc(e.status)} | ${src(e.primary_source)} |`,
    );
  }
  L.push("");

  L.push("## Claims changed / change recommended");
  L.push("");
  if (!changed.length) L.push("_None._");
  else {
    L.push("| ID | Old wording | New wording | Why | Source |");
    L.push("|---|---|---|---|---|");
    for (const e of changed)
      L.push(
        `| ${e.id} | ${esc(e.claim_text)} | ${esc(e.recommended_wording)} | ${esc(e.reviewer_notes)} | ${src(e.primary_source)} |`,
      );
  }
  L.push("");

  L.push("## Needs specialist / legal review");
  L.push("");
  if (!review.length) L.push("_None._");
  else {
    L.push("| ID | Page | Claim | Note |");
    L.push("|---|---|---|---|");
    for (const e of review)
      L.push(`| ${e.id} | ${esc(e.page_url)} | ${esc(e.claim_text)} | ${esc(e.reviewer_notes)} |`);
  }
  L.push("");

  L.push("## Full register (by page)");
  L.push("");
  const pages = [...new Set(entries.map((e) => e.page_url))].sort();
  for (const pg of pages) {
    L.push(`### ${pg}`);
    L.push("");
    for (const e of entries.filter((x) => x.page_url === pg)) {
      L.push(`- **${e.id}** _(${e.risk} · ${e.category} · ${e.status})_ — "${esc(e.claim_text)}"`);
      if (e.recommended_wording) L.push(`  - → **Recommended:** "${esc(e.recommended_wording)}"`);
      L.push(`  - Source: ${src(e.primary_source)}${e.primary_source?.title ? ` — ${esc(e.primary_source.title)}` : ""}`);
      if (e.evidence_summary) L.push(`  - Evidence: ${esc(e.evidence_summary)}`);
      if (e.limitations) L.push(`  - Limitations/context: ${esc(e.limitations)}`);
      if (e.reviewer_notes) L.push(`  - Notes: ${esc(e.reviewer_notes)}`);
      L.push(`  - Last verified ${esc(e.last_verified)}${e.review_due ? ` · review due ${esc(e.review_due)}` : ""}`);
    }
    L.push("");
  }

  await mkdir(path.dirname(OUT_MD), { recursive: true });
  await writeFile(OUT_MD, L.join("\n") + "\n");

  console.log(
    `✓ Register built: ${entries.length} claims (H:${totals.by_risk.HIGH} M:${totals.by_risk.MODERATE} L:${totals.by_risk.LOW}). ` +
      `Changed:${changed.length} Review:${review.length}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
